CODE SEGMENT
ASSUME CS:CODE, DS:DATA

START:
    MOV AX, DATA
    MOV DS, AX

    LEA DX, MSG
    MOV AH, 09H
    INT 21H

    MOV SI, 0
    MOV CX, 5

PUSH_LOOP:
    MOV AL, ARR[SI]
    MOV AH, 0
    PUSH AX
    INC SI
    LOOP PUSH_LOOP

    MOV CX, 5
    POP AX
    MOV BL, AL

POP_LOOP:
    POP AX
    CMP AL, BL
    JLE SKIP
    MOV BL, AL

SKIP:
    LOOP POP_LOOP

    ADD BL, 30H
    MOV DL, BL
    MOV AH, 02H
    INT 21H

    MOV AH, 4CH
    INT 21H

CODE ENDS
END START