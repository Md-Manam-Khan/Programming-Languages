public class aaab_JavaVariables
{
    public static void main(String[] args)
    {
        int n = 5;
        double d = 50.60;
        char c = 'a';
        boolean b = true;
        System.out.println("The int is: " + n);
        System.out.println("The double is: " + d);
        System.out.println("The char is: " + c);
        System.out.println("The boolean is: " + b);
    }
}